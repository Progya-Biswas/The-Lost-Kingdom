#!/usr/bin/env python3
"""Regenerate gui/font_data.hpp: an 8x16 1-bit bitmap font (ASCII 32..126)
rasterised from DejaVu Sans Mono (free licence, see Bitstream Vera/DejaVu)."""
import sys
from PIL import Image, ImageDraw, ImageFont

path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
font = ImageFont.truetype(path, 13)
W, H = 8, 16
rows = []
for code in range(32, 127):
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, 1), chr(code), font=font, fill=255)
    px = img.load()
    rows.append([sum((1 << (7 - x)) for x in range(W) if px[x, y] > 90) for y in range(H)])

with open("gui/font_data.hpp", "w") as out:
    out.write("// Generated by tools/gen_font.py - do not edit by hand.\n#pragma once\n#include <cstdint>\n\n")
    out.write("namespace lostkingdom::gui {\nconstexpr int FONT_W = 8, FONT_H = 16, FONT_FIRST = 32, FONT_LAST = 126;\n")
    out.write("constexpr std::uint8_t FONT_DATA[][FONT_H] = {\n")
    for r in rows:
        out.write("    {" + ",".join("0x%02x" % b for b in r) + "},\n")
    out.write("};\n}\n")
